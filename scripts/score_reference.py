ANN = 365 / 30                         # 30일 값을 연환산하는 계수 = 12.1667
BANDS = [(12, "S+"), (8, "S"), (5, "A"), (3, "B+"), (1.5, "B"), (0.4, "C")]   # 미만이면 D
K_ACC_DEFAULT = {"순수 수수료 소각": 1.00, "매수 후 소각": 1.00, "매수 후 분배": 1.00,
                 "직접 수수료 분배": 1.00, "매수 후 소각·분배": 1.00, "매수 후 보유": 0.35}
K_AUTO_DEFAULT = {"코드 자동": 1.00, "정기 집행": 0.90, "불규칙": 0.65, "정지": 0.00}


def grade(adj, bands=BANDS):
    for th, g in bands:
        if adj >= th:
            return g
    return "D"


def score_one(tok, price, hr30, hr7, k_acc, k_auto, lumpy):
    """종목 정의 tok(universe.json 의 tokens[i])와 주간 입력으로 행 하나를 만든다."""
    circ, fdv, inc = tok["circ"], tok["fdv"], tok.get("inc30")
    mc = price * circ / 1e6                                  # 시가총액, 백만 달러
    raw = (hr30 / 1e6) / mc * 100 * ANN                      # 원시 캡처율 %
    netv = (hr30 / 1e6 - inc) if inc is not None else (hr30 / 1e6)
    net = netv / mc * 100 * ANN                              # 순 캡처율 %
    rr = (hr7 * 30 / 7) / hr30 if hr30 else None             # 7일 런레이트 ÷ 30일

    if hr30 == 0:
        ks, stab = 0.0, "실현 0"
    elif tok["t"] in lumpy:
        ks, stab = 0.90, "주기형"
    else:
        ks = max(0.30, min(1.00, rr))
        stab = "가속" if rr > 1.15 else ("감속" if rr < 0.85 else "안정")
    ka = k_acc[tok["acc"]]
    ku = k_auto[tok["auto"]]
    kd = max(0.40, (1.0 / fdv) ** 0.5)
    kh = tok["hist_k"]

    # 음수 규칙(2026-09-17 ②안): 순 캡처율이 음수이면 계수를 곱하지 않는다.
    # 할인 계수를 음수에 곱하면 값이 0 쪽으로 올라가 점수가 좋아지기 때문이다.
    adj = net if net < 0 else net * ka * ku * ks * kd * kh

    return {
        "t": tok["t"], "n": tok["n"], "slug": tok["slug"], "cg": tok["cg"],
        "mc": round(mc, 3), "fdv": fdv, "price": price, "hr30": hr30, "hr7": hr7,
        "rr": (round(rr, 3) if rr is not None else None),
        "raw": round(raw, 3), "net": round(net, 3), "adj": round(adj, 3), "g": grade(adj),
        "inc": inc, "ver": inc is not None,
        "acc": tok["acc"], "auto": tok["auto"], "stab": stab,
        "k": {"acc": ka, "auto": ku, "stab": round(ks, 3), "dil": round(kd, 4), "hist": kh},
        "hist": tok["hist"], "note": tok["note"],
    }


def score(universe, inputs, date, overrides=None):
    """
    universe : universe.json 을 읽은 dict
    inputs   : {sym: [price, hr30, hr7]} 또는 {sym: {"price":..,"hr30":..,"hr7":..}}
    overrides: {sym: {필드: 값}} 종목 정의를 이번 계산에서만 덮어쓸 때(선택)
    반환     : {"date": date, "rows": [...]}  (조정 캡처율 내림차순)
    inputs 에 없는 종목은 건너뛴다. 수집 실패 종목을 스냅샷에서 빼는 규칙과 같다.
    """
    f = universe["formula"]
    k_acc = f.get("k_acc", K_ACC_DEFAULT)
    k_auto = f.get("k_auto", K_AUTO_DEFAULT)
    lumpy = set(f.get("lumpy", []))
    rows = []
    for tok in universe["tokens"]:
        sym = tok["t"]
        if sym not in inputs:
            continue
        x = inputs[sym]
        price, hr30, hr7 = (x["price"], x["hr30"], x["hr7"]) if isinstance(x, dict) else x
        if overrides and sym in overrides:
            tok = dict(tok, **overrides[sym])
        rows.append(score_one(tok, price, hr30, hr7, k_acc, k_auto, lumpy))
    rows.sort(key=lambda r: -r["adj"])
    return {"date": date, "rows": rows}


def print_table(snap):
    print(f"{'':3}{'종목':7}{'등급':>4}{'조정%':>9}{'순%':>9}{'원시%':>9}{'시총$M':>11}{'RR':>7}  {'추세':6}{'귀속방식'}")
    for i, r in enumerate(snap["rows"], 1):
        rr = "-" if r["rr"] is None else f"{r['rr']:.2f}"
        print(f"{i:<3}{r['t']:7}{r['g']:>4}{r['adj']:>9.2f}{r['net']:>9.2f}{r['raw']:>9.2f}"
              f"{r['mc']:>11.1f}{rr:>7}  {r['stab']:6}{r['acc']}")
    from collections import Counter
    print("등급 분포:", dict(Counter(r["g"] for r in snap["rows"])))


